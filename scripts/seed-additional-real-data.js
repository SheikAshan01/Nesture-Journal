async function main() {
  console.log('[Seed] Seeding 10 additional authentic real-world news articles...');
  const author = await prisma.author.findFirst();
  if (!author) {
    console.error('No author found in database!');
    process.exit(1);
  }

  for (const art of ADDITIONAL_ARTICLES) {
    const category = await prisma.category.findUnique({
      where: { slug: art.categorySlug },
    });

    if (!category) {
      console.warn(`Category ${art.categorySlug} not found, skipping.`);
      continue;
    }

    await prisma.article.upsert({
      where: { slug: art.slug },
      update: {
        title: art.title,
        shortDescription: art.shortDescription,
        content: art.content,
        featuredImage: art.featuredImage,
        imageAlt: art.imageAlt,
        status: art.status,
        isFeatured: art.isFeatured,
        isTrending: art.isTrending,
        isBreaking: art.isBreaking,
        readingTime: art.readingTime,
        seoTitle: art.seoTitle,
        seoDescription: art.seoDescription,
        sourceName: art.sourceName,
        sourceUrl: art.sourceUrl,
        publicationDate: new Date(),
        updatedDate: new Date(),
      },
      create: {
        title: art.title,
        slug: art.slug,
        shortDescription: art.shortDescription,
        content: art.content,
        featuredImage: art.featuredImage,
        imageAlt: art.imageAlt,
        categoryId: category.id,
        authorId: author.id,
        status: art.status,
        isFeatured: art.isFeatured,
        isTrending: art.isTrending,
        isBreaking: art.isBreaking,
        readingTime: art.readingTime,
        seoTitle: art.seoTitle,
        seoDescription: art.seoDescription,
        sourceName: art.sourceName,
        sourceUrl: art.sourceUrl,
        publicationDate: new Date(),
        updatedDate: new Date(),
      },
    });
    console.log(`✓ Seeded: [${category.name}] ${art.title}`);
  }

  const total = await prisma.article.count();
  console.log(`\n[Seed] Complete! Total articles in DB: ${total}`);
  await prisma.$disconnect();
}

main().catch(console.error);
